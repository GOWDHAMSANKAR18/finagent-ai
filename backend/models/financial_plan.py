from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional

class MonthlyAllocationItem(BaseModel):
    category: str
    allocated_amount: float
    percentage_of_income: float
    explanation: str

class GoalAnalysisResult(BaseModel):
    goal_name: str
    target_amount: float
    deadline_months: int
    required_monthly: float
    allocated_monthly: float
    feasible: bool
    feasibility_status: str
    gap_per_month: float
    timeline_recommendation: str

class RiskWarningItem(BaseModel):
    severity: str  # Critical, Warning, Info
    risk_title: str
    description: str
    recommended_action: str

class AgentContributionTrace(BaseModel):
    agent_name: str
    role: str
    key_findings: List[str]
    confidence_score: float

class FinancialPlanOutput(BaseModel):
    summary: Dict[str, Any]
    budget_breakdown: Dict[str, Any]
    goal_evaluations: List[GoalAnalysisResult]
    debt_evaluation: Dict[str, Any]
    risk_assessment: List[RiskWarningItem]
    proposed_monthly_plan: List[MonthlyAllocationItem]
    action_plan: List[str]
    agent_contributions: List[AgentContributionTrace]
    citations_and_sources: List[Dict[str, Any]]
    disclaimer: str = "This output is generated by an academic multi-agent AI assistant for educational financial planning. It does not constitute regulated financial advice."
